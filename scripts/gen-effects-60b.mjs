// Generates src/protocol/effects60b.generated.ts from g200kg/zoom-ms-utility
// js/effectslist.js (MIT). Usage:
//   node scripts/gen-effects-60b.mjs <path/to/effectslist.js> <g200kg commit hash>
// The source is a pure data file; it is evaluated in an empty VM context.
import { readFileSync, writeFileSync } from 'node:fs'
import vm from 'node:vm'

const [src, commit] = process.argv.slice(2)
if (!src || !commit) {
  console.error('usage: node scripts/gen-effects-60b.mjs <effectslist.js> <commit>')
  process.exit(1)
}
const ctx = vm.createContext({})
vm.runInContext(readFileSync(src, 'utf8') + '\n;globalThis.__out = effectlist; globalThis.bampcabmax = bampcabmax; globalThis.bampcabdisp = bampcabdisp; globalThis.gampcabmax = gampcabmax; globalThis.gampcabdisp = gampcabdisp;', ctx, { timeout: 1000 })
const all = ctx.__out

// Decode numeric HTML entities (g200kg uses &#x1D15F; etc. for note symbols).
const decodeEntities = (t) =>
  t.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))

function convertParam(p, effectName) {
  const r = { name: p.name, def: p.def }
  if (p.max === ctx.bampcabmax) r.range = { kind: 'cab', table: 'bass' }
  else if (p.max === ctx.gampcabmax) r.range = { kind: 'cab', table: 'guitar' }
  else if (typeof p.max === 'number') r.range = { kind: 'linear', max: p.max }
  else throw new Error(`unexpected max in ${effectName}/${p.name}`)

  const d = p.disp
  if (d === undefined || d === ctx.bampcabdisp || d === ctx.gampcabdisp) {
    // no disp, or cab labels resolved from firmwareTables.ts
  } else if (typeof d === 'number' || Array.isArray(d)) {
    r.disp = d
  } else if (d && d.type === 'Time') {
    r.disp = { kind: 'time', min: d.min, max: d.max, list: d.list.map(decodeEntities) }
  } else {
    throw new Error(`unexpected disp in ${effectName}/${p.name}`)
  }
  if (p.dispr !== undefined) r.dispr = p.dispr
  for (const k of Object.keys(p)) {
    if (!['name', 'def', 'max', 'disp', 'dispr'].includes(k)) {
      throw new Error(`unknown param field ${k} in ${effectName}/${p.name}`)
    }
  }
  return r
}

const out = []
for (const [key, ef] of Object.entries(all)) {
  const v60 = (ef.ver >> 4) & 0xf
  const id = Number(key)
  // THRU (id 0) has ver 0x0101 -> not flagged for 60B, but every patch can hold it.
  if (v60 === 0 && id !== 0) continue
  out.push({
    id,
    name: ef.name,
    group: ef.group,
    order: ef.order,
    minFirmware: v60,
    dsp: ef.dsp,
    dspmax: ef.dspmax,
    dspmin: ef.dspmin,
    params: ef.param.map((p) => convertParam(p, ef.name)),
  })
}
out.sort((a, b) => a.order - b.order)

const header = `/*
 * GENERATED FILE — do not edit by hand.
 * Generated by scripts/gen-effects-60b.mjs from js/effectslist.js of
 * g200kg/zoom-ms-utility, commit ${commit}, filtered to MS-60B effects
 * ((ver >> 4) & 0xF != 0) plus THRU.
 *
 * MIT License
 * Copyright (c) 2017 — zoom-ms-utility by g200kg (original LICENSE names no holder)
 * See THIRD_PARTY_NOTICES.md for the full license text.
 *
 * Field notes (from g200kg's code, unverified against the pedal):
 *  - params[i] maps to patch value fx[n][i + 2].
 *  - range 'cab': allowed values come from firmwareTables.ts (by firmware version).
 *  - disp: labels, numeric offset (with optional dispr ratio), or time display.
 *    Note symbols in time lists were HTML entities in the source; decoded here.
 *  - dsp/dspmax/dspmin: g200kg's own estimate; usage % = 100 / dsp.
 *  - minFirmware: lowest firmware major version that has the effect.
 *  - Names here are g200kg's; all 142 match Zoom's "Effect Types and Parameters (Ver.2)" (docs/E_MS-60B_FX-list_v2.pdf).
 */
import type { EffectDef } from './effectTypes'

export const EFFECTS_60B: readonly EffectDef[] = `
writeFileSync(
  'src/protocol/effects60b.generated.ts',
  header + JSON.stringify(out, null, 2) + '\n',
)
console.log(`wrote ${out.length} effects`)
