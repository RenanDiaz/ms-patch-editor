// Builds a differential-test oracle: runs g200kg's own apatch.ReadBin
// (js/apatch.js, MIT) on pseudo-random 105-byte MS-60B patches and writes the
// decoded fields to src/protocol/__tests__/g200kg-readbin-golden.json.
// These bytes are NOT from a pedal; they only check the port matches g200kg.
// Usage: node scripts/gen-golden-readbin.mjs <path/to/apatch.js> <commit> [capture.json]
// With a capture file (real pedal bytes, ms60b-capture/1), the oracle is built
// from those patches instead and written to g200kg-readbin-real.json.
import { readFileSync, writeFileSync } from 'node:fs'
import vm from 'node:vm'

const [src, commit, capturePath] = process.argv.slice(2)
if (!src || !commit) {
  console.error('usage: node scripts/gen-golden-readbin.mjs <apatch.js> <commit>')
  process.exit(1)
}
const ctx = vm.createContext({})
vm.runInContext(readFileSync(src, 'utf8') + '\n;globalThis.__apatch = apatch;', ctx, { timeout: 1000 })
const Apatch = ctx.__apatch

// mulberry32, fixed seed → reproducible output
let seed = 0x60b
function rnd() {
  seed |= 0; seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}

const capture = capturePath ? JSON.parse(readFileSync(capturePath, 'utf8')) : null
const inputs = capture
  ? capture.patches.map((h) => h.split(' ').map((x) => parseInt(x, 16)))
  : [Array.from(Apatch.prototype.empty105)]
for (let i = 0; !capture && i < 200; i++) {
  const b = [0xf0, 0x52, 0x00, 0x5f, 0x28]
  for (let j = 5; j < 104; j++) b.push(Math.floor(rnd() * 128))
  b.push(0xf7)
  inputs.push(b)
}
const cases = inputs.map((bytes) => {
  const p = new Apatch()
  p.ReadBin(bytes)
  return {
    bytes,
    name: p.name,
    fx: p.fx.slice(0, 4).map((f) => Array.from(f)),
    maxfx: p.maxfx,
    curfx: p.curfx,
    dspstate: p.dspstate,
  }
})
const outFile = capture
  ? 'src/protocol/__tests__/g200kg-readbin-real.json'
  : 'src/protocol/__tests__/g200kg-readbin-golden.json'
writeFileSync(
  outFile,
  JSON.stringify({
    _note: capture
      ? `g200kg ReadBin output for the real capture ${capturePath.split('/').pop()}. Generated by scripts/gen-golden-readbin.mjs with g200kg/zoom-ms-utility js/apatch.js @ ${commit} (MIT).`
      : `Derived oracle, not pedal data. Generated by scripts/gen-golden-readbin.mjs with g200kg/zoom-ms-utility js/apatch.js @ ${commit} (MIT).`,
    cases,
  }) + '\n',
)
console.log(`wrote ${cases.length} cases`)
